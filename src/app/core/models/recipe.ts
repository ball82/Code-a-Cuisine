import { Ingredient } from './ingredient';
import { Cuisine } from './recipe-request';

/** Nutrition values – strictly per portion (the frontend computes totals = value × portions). */
export interface NutritionPerPortion {
  calories: number;
  protein: number;
  fat: number;
  carbs: number;
}

/** A single cooking step. */
export interface Direction {
  step: number;
  title: string;
  /** Number 1–3, maps to "Chef 1/2/3". With 1 cook: all steps chef: 1. */
  chef: number;
  instruction: string;
  /**
   * Marks a step that runs in parallel to the previous one (e.g. during a
   * waiting time in the oven or handled simultaneously by a second cook).
   * Optional: older recipes without this field are treated as purely sequential.
   */
  parallel?: boolean;
}

/** Contract 2 — a recipe generated by Gemini and stored in Firestore. */
export interface Recipe {
  /** Firestore auto ID. */
  id: string;
  title: string;
  cuisine: Cuisine;
  tags: string[];
  cookingTimeMinutes: number;
  portions: number;
  cooks: number;
  nutritionPerPortion: NutritionPerPortion;
  /** Ingredients contributed by the user. */
  yourIngredients: Ingredient[];
  /** Additionally required ingredients (at most 3). */
  extraIngredients: Ingredient[];
  directions: Direction[];
  likes: number;
  /** ISO timestamp. */
  createdAt: string;
}

/** Contract 2 — response from n8n to Angular: exactly 3 recipes with IDs. */
export interface RecipeResponse {
  recipes: Recipe[];
  /**
   * Remaining generations for the IP on this day (US11 transparency).
   * Optional: older backend versions do not provide this field yet.
   */
  remaining?: number;
}
